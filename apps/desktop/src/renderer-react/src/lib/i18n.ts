const DICTS: Record<Locale, Dict> = { en, zh };

/** Pure translation lookup. Falls back zh→en→key, with {name} interpolation. */
export function translate(locale: Locale, key: string, vars?: Vars): string {
  const template = DICTS[locale]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    name in vars ? String(vars[name]) : match,
  );
}

export type TFunc = (key: string, vars?: Vars) => string;

/**
 * Reactive translator hook. Subscribes the calling component to the `language`
 * view-setting, so changing the language in settings re-renders every consumer
 * immediately (no restart, matching the legacy behavior).
 */
export function useT(): TFunc {
  const { language } = useViewSettings();
  // Stable per language: several panels hold `t` in useCallback/useEffect dep
  // arrays (SkillsPanel loadSkills, GeneralPanel, PermissionsPanel, RulesPanel).
  // A fresh closure every render re-armed those effects every render — each
  // load flipped state, re-rendered, minted a new `t`, and re-fired the load:
  // an endless refetch loop (the Skills panel's flashing "加载中…" button).
  return useCallback((key, vars) => translate(language, key, vars), [language]);
}
