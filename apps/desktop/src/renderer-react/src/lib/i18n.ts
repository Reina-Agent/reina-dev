// Lightweight i18n for the React renderer (settings + workspace windows).
//
// The legacy plain-JS renderer has its own dictionary in
// `apps/desktop/src/renderer/i18n.js` driven by `setLocale()` + `data-i18n`
// attributes. The React renderer never consumed the `language` view-setting at
// all — it only stored it — so switching the dropdown did nothing visible.
//
// This module closes that gap WITHOUT importing the DOM-attribute machinery:
// React components subscribe to the language via `useT()`, which reads the
// reactive `language` view-setting and re-renders the calling component on
// change. Chinese strings are ported from the legacy `zh` dictionary so wording
// stays consistent across both renderers. Keys missing from `zh` fall back to
// `en`; keys missing from both fall back to the key itself.

